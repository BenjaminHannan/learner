"""gen_gr5_box.py SHA: write gpu_run_5_box.sh = results/8a-g/vast-ptc3s/ptc3s_box.sh (the reviewed GPU-RUN-3 box script) plus one new plan, PROF_PLAN=gr5 (GPU-RUN-5,
PREREG-gpu-run-5.md, per the coordinator's ruling of 10-20): after the same setup / code / gemma / data / skills stages and the same pool-building smoke, ONE harness step, g1_e4floor =
launch/e4floor.py (six fresh 300-update traces B,D,B,D,B,D), with launch/hostmon.sh throughout. Every edit is an exact text replacement that must match once. SHA = the commit of branch
claude/launch-bound-solve whose results/8a-g/speedup/ the box fetches; the sha256 of every file the box runs from it is pinned. Usage: python gen_gr5_box.py <full commit sha>."""
import hashlib, os, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = subprocess.run(['git', '-C', HERE, 'rev-parse', '--show-toplevel'], capture_output=True, text=True, check=True).stdout.strip()
SRC = os.path.join(REPO, 'results/8a-g/vast-ptc3s/ptc3s_box.sh')
OUT = os.path.join(HERE, 'gpu_run_5_box.sh')
PROF_PY_SHA_REVIEWED = '27741d82faeb6f7b149f47022e1a0cde780a02cf34283d9102841726ba25bd6c'
LAUNCH_FILES = ('prof_launch.py', 'defer.py', 'exact_arms.py', 'hostmon.sh', 'e4floor.py')


def blob_sha(sha, path):
    return hashlib.sha256(subprocess.run(['git', '-C', REPO, 'show', f'{sha}:{path}'], capture_output=True, check=True).stdout).hexdigest()


def edit(s, old, new):
    n = s.count(old)
    if n != 1:
        raise SystemExit(f'gen_gr5_box: expected exactly one match, found {n}: {old[:120]!r}')
    return s.replace(old, new)


def main():
    sha = sys.argv[1]
    assert len(sha) == 40, 'give the full 40-character commit sha'
    py = blob_sha(sha, 'results/8a-g/speedup/prof/prof_train.py')
    if py != PROF_PY_SHA_REVIEWED:
        raise SystemExit(f'prof_train.py at {sha} is {py}, not the reviewed {PROF_PY_SHA_REVIEWED}')
    pins = {f: blob_sha(sha, f'results/8a-g/speedup/launch/{f}') for f in LAUNCH_FILES}
    s = open(SRC).read()
    s = edit(s, '# PROF_PLAN=b3ab (needs PROFILE=1; added 2026-10-14)',
             '# PROF_PLAN=gr5 (needs PROFILE=1; added 2026-10-20, generated by results/8a-g/speedup/launch/gen_gr5_box.py): GPU-RUN-5 of results/8a-g/speedup/launch/PREREG-gpu-run-5.md\n'
             '# (the coordinator\'s ruling of 10-20 on the E4 noise floor). Same stages setup, code, gemma, data, skills and the same pool-building smoke (50 updates) as b3ab. Then ONLY\n'
             '# g1_e4floor: launch/e4floor.py, six fresh 300-update loss traces of B3G2 3M accum 4 in the order B,D,B,D,B,D (baseline / defer), same seed, rows and pinned stochastic parts,\n'
             '# with launch/hostmon.sh writing hostmon.csv every 10 s. Defaults: MAXH 1.75; gr5 refuses DPH=0 and MAXH x DPH above PROF_STAGE_CAP_USD (default 0.82 = 1.75 h x $0.47/h);\n'
             '# GR5_MIN (60): the step timeout in minutes. The ruling\'s hard cap of $1.00 is the BILLED total: the operator destroys the box by that time (GPU-RUN-5-booking.md).\n'
             '# PROF_PLAN=b3ab (needs PROFILE=1; added 2026-10-14)')
    s = edit(s, '[ "$PROFILE" = 1 ] && [ "$PROF_PLAN" = b3ab ] && D_MAXH=5.5',
             '[ "$PROFILE" = 1 ] && [ "$PROF_PLAN" = b3ab ] && D_MAXH=5.5\n[ "$PROFILE" = 1 ] && [ "$PROF_PLAN" = gr5 ] && D_MAXH=1.75')
    s = edit(s, 'PROF_PY_SHA=a078a8d6e3bd7733ed183562e7ea91d98e4040daea29a073de5370d7afd04af3    # sha256 of prof/prof_train.py at PROF_SHA\n',
             'PROF_PY_SHA=a078a8d6e3bd7733ed183562e7ea91d98e4040daea29a073de5370d7afd04af3    # sha256 of prof/prof_train.py at PROF_SHA\n'
             f'GR5_SHA={sha}          # PROF_PLAN=gr5: branch claude/launch-bound-solve, results/8a-g/speedup (prof/ + launch/)\n'
             f'if [ "$PROF_PLAN" = gr5 ]; then PROF_SHA=$GR5_SHA; PROF_PY_SHA={py}; fi    # prof_train.py at GR5_SHA = the reviewed df64d00a0 file\n'
             + ''.join(f'GR5_PIN_{f.replace(".", "_").upper()}={h}      # sha256 of launch/{f} at GR5_SHA\n' for f, h in pins.items()))
    s = edit(s, "if [ \"$PROF_PLAN\" = b3ab ]; then D_PMAX=285; D_PJOBMIN=20; D_PJOBSTEPS=50; D_PLOGE='--log-every 10'",
             "if [ \"$PROF_PLAN\" = gr5 ]; then D_PMAX=75; D_PJOBMIN=20; D_PJOBSTEPS=50; D_PLOGE='--log-every 10'      # plan gr5: smoke about 6 min + six traces about 45 min\n"
             "elif [ \"$PROF_PLAN\" = b3ab ]; then D_PMAX=285; D_PJOBMIN=20; D_PJOBSTEPS=50; D_PLOGE='--log-every 10'")
    gr5 = r'''prof_gr5() {   # PROF_PLAN=gr5 (POOL is set): GPU-RUN-5 (PREREG-gpu-run-5.md): e4floor.py, non-fatal under its own timeout; hostmon.sh throughout
  local L=$J/prof/$PROF_DIR/launch f h want B3 HM
  for f in prof_launch.py defer.py exact_arms.py hostmon.sh e4floor.py; do
    h=$(sha $L/$f); want=$(eval echo \$GR5_PIN_$(echo $f | tr . _ | tr a-z A-Z))
    [ "$h" = "$want" ] || { say "PROF GR5 FAILED: launch/$f is $h, not the pinned $want: no gr5 run"; PFAIL="$PFAIL gr5-pin($f)"; return 0; }
  done
  say "PROF-GR5 launch files pinned: $(for f in prof_launch.py defer.py exact_arms.py hostmon.sh e4floor.py; do echo -n "$f=$(sha $L/$f | cut -c1-12) "; done)"
  mkdir -p $PRAW; HM=; bash $L/hostmon.sh $PRAW/hostmon.csv 10 'python[0-9.]* .*e4floor[.]py' & HM=$!
  { echo "# GPU-RUN-5 host: $(hostname)"; grep -m1 'model name' /proc/cpuinfo; nproc; [ "$PTC_DRY" = 1 ] || nvidia-smi --query-gpu=name,driver_version,memory.total,power.limit,clocks.max.sm --format=csv; python -c 'import torch; print("torch", torch.__version__, "cuda", torch.version.cuda, "cudnn", torch.backends.cudnn.version())'; } > $PRAW/gr5_host.txt 2>&1
  cut -c1-200 $PRAW/gr5_host.txt
  PY=$L/e4floor.py
  B3="--arm B3G2 --rung 3M --accum 4 --data $POOL --pkg-root $S --caps $S/custom_io/g8a/caps_b3g2.json"
  say "PROF PLAN gr5: B3G2 3M accum 4; six fresh 300-update E4 traces B,D,B,D,B,D (baseline / defer); DPH=$DPH; budget $PROF_MAXMIN min"
  PSTEP_MIN=${GR5_MIN:-60}; pstep g1_e4floor gr5_e4floor.json $B3 --curve-updates 300
  PSTEP_MIN=
  grep -E 'e4floor (trace|done|:)' $PRAW/g1_e4floor.log 2>/dev/null | tail -n 16 | cut -c1-200
  [ -n "$HM" ] && { kill $HM 2>/dev/null; wait $HM 2>/dev/null; }
  awk -v up=$(( $(date +%s) - T0 )) -v dph=$DPH -v maxh=$MAXH 'BEGIN{printf "PROF COST DPH=%s USD/h: up %.1f min = %.2f USD so far; MAXH %s h ceiling = %.2f USD (the rental, from DPH x time, not a bill)\n", dph, up/60, up/3600*dph, maxh, maxh*dph}'
}
prof_main() {   # never returns: ends with CIO DONE / CIO-FAIL and a sleep'''
    s = edit(s, 'prof_main() {   # never returns: ends with CIO DONE / CIO-FAIL and a sleep', gr5)
    s = edit(s, '    if [ "$PROF_PLAN" = b3ab ]; then prof_b3ab; elif [ "$PROF_PLAN" = b3sweep ]; then prof_b3sweep; else',
             '    if [ "$PROF_PLAN" = gr5 ]; then prof_gr5; elif [ "$PROF_PLAN" = b3ab ]; then prof_b3ab; elif [ "$PROF_PLAN" = b3sweep ]; then prof_b3sweep; else')
    s = edit(s, 'case $PROF_PLAN in default) ;; b3sweep|b3ab) [ "$PROFILE" = 1 ] || { FAIL_SLEEP=120; die "PROF_PLAN=$PROF_PLAN needs PROFILE=1"; };; *) FAIL_SLEEP=120; die "PROF_PLAN must be default, b3sweep or b3ab (got \'$PROF_PLAN\')";; esac',
             'case $PROF_PLAN in default) ;; b3sweep|b3ab|gr5) [ "$PROFILE" = 1 ] || { FAIL_SLEEP=120; die "PROF_PLAN=$PROF_PLAN needs PROFILE=1"; };; *) FAIL_SLEEP=120; die "PROF_PLAN must be default, b3sweep, b3ab or gr5 (got \'$PROF_PLAN\')";; esac\n'
             'if [ "$PROF_PLAN" = gr5 ]; then\n'
             '  GCAP=${PROF_STAGE_CAP_USD:-0.82}\n'
             '  [ "$DPH" != 0 ] || { FAIL_SLEEP=120; die "PROF_PLAN=gr5 needs DPH (the offer\'s dph_total)"; }\n'
             '  awk "BEGIN{exit !($MAXH * $DPH > $GCAP + 1e-9)}" && { FAIL_SLEEP=120; die "PROF_PLAN=gr5: MAXH x DPH = $(awk "BEGIN{print $MAXH * $DPH}") USD is above the cap $GCAP USD (PREREG-gpu-run-5.md money)"; }\n'
             '  say "PROF GR5 MAXH=$MAXH DPH=$DPH: ceiling $(awk "BEGIN{print $MAXH * $DPH}") USD <= cap $GCAP USD"\n'
             'fi')
    open(OUT, 'w').write(s)
    os.chmod(OUT, 0o755)
    print(OUT, hashlib.sha256(s.encode()).hexdigest(), 'GR5_SHA', sha, {k: v[:12] for k, v in pins.items()})


if __name__ == '__main__':
    main()
