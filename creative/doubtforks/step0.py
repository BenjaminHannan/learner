"""Doubt Forks Step 0 gate (INVENT-2 Pick 1). No training. Needs only a vLLM server (prompt_logprobs) and the Guess-1 results.

  python step0.py --results <guess1 out>/run/results.jsonl --base-url http://127.0.0.1:8080/v1 --model k2 \
      --tokenizer IFM/K2-Horizon-3.7B --out <dir>
Writes gate.json, gate.md, forks.jsonl (every candidate, survivor flag), token_stats.jsonl (p1, p2, entropy per assistant token).
Labels in the report: shown = measured here; suggested = heuristic choice made here; untested = not checked.
"""
import argparse, ast, asyncio, bisect, json, math, os, random, re, sys
from collections import Counter, defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
R1 = os.path.join(os.path.dirname(HERE), "reach1")
sys.path.insert(0, R1)
from episode import SYSTEM  # noqa: E402  (also puts rlaif_copy on sys.path)
from sandbox import World, TOOLS  # noqa: E402

P1_MIN, P2_MIN, TOPK, ALIAS_TOKENS = 0.9, 0.005, 20, 24
PER_TASK, PREFIXES_PER_TYPE, G1_FORKS, G1_SHARE, MAX_LEN = 2, 20, 8, 0.70, 15000
TYPES = ("TURN-START", "TOOL-NAME", "ARG-VALUE")
TURN = re.compile(r"<\|ifm\|im_start\|>assistant\n<ifm\|think(?:_fast|_faster)?>\n.*?</ifm\|think(?:_fast|_faster)?>", re.S)
END, TC, AV, AVE, TCS = "<|ifm|im_end|>", "<ifm|tool_call>", "<ifm|arg_value>", "</ifm|arg_value>", "<ifm|tool_calls>"


# ---------- rendering ----------
def build_messages(task, rec):
    """Rebuild the exact message list the server saw. Returns None if a tool call has non-dict arguments (the template needs dicts)."""
    system = SYSTEM.format(today=World.from_json(task["state"]).today) + (("\n\n" + rec["extra_block"]) if rec.get("extra_block") else "")
    msgs = [dict(role="system", content=system)]
    for m in rec["transcript"]:
        m = dict(m)
        if m.get("tool_calls"):
            tcs = []
            for c in m["tool_calls"]:
                f = dict(c["function"])
                a = f.get("arguments")
                if isinstance(a, str):
                    try:
                        a = json.loads(a) if a.strip() else {}
                    except json.JSONDecodeError:
                        return None
                if not isinstance(a, dict):
                    return None
                tcs.append(dict(c, function=dict(f, arguments=a)))
            m["tool_calls"] = tcs
        msgs.append(m)
    return msgs


class HFTok:
    def __init__(self, name, template_path):
        from transformers import AutoTokenizer
        self.t = AutoTokenizer.from_pretrained(name, trust_remote_code=True)
        self.template = open(template_path).read()

    def render(self, msgs, tools):
        return self.t.apply_chat_template(msgs, tools=tools, tokenize=False, chat_template=self.template)

    def encode(self, text):
        e = self.t(text, add_special_tokens=False, return_offsets_mapping=True)
        return list(e["input_ids"]), [tuple(o) for o in e["offset_mapping"]]

    def decode(self, ids):
        return self.t.decode(ids, skip_special_tokens=False)


# ---------- spans -> decision tokens ----------
def spans(text):
    """Char spans of the decision points inside assistant turns of the rendered text (K2 xml tool-call layout)."""
    out = []
    for ti, m in enumerate(TURN.finditer(text)):
        s = m.end()
        e = text.find(END, s)
        e = len(text) if e < 0 else e
        out.append(dict(type="TURN-START", start=s, end=e, turn=ti))
        for tag, typ in ((TC, "TOOL-NAME"), (AV, "ARG-VALUE")):
            for x in re.finditer(re.escape(tag), text[s:e]):
                st = s + x.end()
                if st >= e or text[st] == "\n" or text.startswith(AVE, st):
                    continue  # empty name / empty value: nothing to fork
                out.append(dict(type=typ, start=st, end=e, turn=ti))
    return out


def type_tokens(offsets, sp):
    """-> (decision list of dict(span, pos), n_straddle). pos = first token that starts exactly at the span start; a token straddling it is skipped."""
    ends = [o[1] for o in offsets]
    res, strad = [], 0
    for s in sp:
        i = bisect.bisect_right(ends, s["start"])  # first token with end > start
        if i >= len(offsets):
            continue
        if offsets[i][0] != s["start"]:
            strad += 1
            continue
        res.append(dict(span=s, pos=i))
    return res, strad


def assistant_mask(text, offsets):
    """True for tokens generated by the assistant (after the think-close tag through the im_end token)."""
    regions = []
    for m in TURN.finditer(text):
        e = text.find(END, m.end())
        regions.append((m.end(), len(text) if e < 0 else e + len(END)))
    starts = [r[0] for r in regions]
    mask = []
    for a, _ in offsets:
        j = bisect.bisect_right(starts, a) - 1
        mask.append(j >= 0 and a < regions[j][1])
    return mask


# ---------- logprobs ----------
def lp_stats(entry):
    """vLLM prompt_logprobs entry {token_id(str): {logprob, ...}} -> (top list [(id, p)], p1, p2, entropy over the top-20)."""
    top = sorted(((int(k), math.exp(v["logprob"] if isinstance(v, dict) else v)) for k, v in entry.items()), key=lambda x: -x[1])[:TOPK]
    p1 = top[0][1] if top else 0.0
    p2 = top[1][1] if len(top) > 1 else 0.0
    return top, p1, p2, -sum(p * math.log(p) for _, p in top if p > 0)


def is_candidate(p1, p2, actual_is_top=True):
    """Doubt-Fork candidate: a confident choice that was actually taken (argmax) with a live runner-up."""
    return bool(actual_is_top and p1 >= P1_MIN and p2 >= P2_MIN)


# ---------- alias filter ----------
def norm(s):
    return " ".join(str(s).lower().replace("\u2019", "'").split()).strip(" '\"`")


def turn_type(s):
    s = s.split(END)[0]
    return "tool" if TCS in s or TC in s else ("ask" if "?" in s else "answer")


def tool_name(s):
    return norm(re.split(r"[\n<]", s.split(END)[0].lstrip(), maxsplit=1)[0])


def arg_value(s):
    s = s.split(END)[0]
    i = s.find(AVE)
    return (norm(s[:i]), True) if i >= 0 else (norm(s), False)


def differs(typ, a, b):
    """True if the forced span b means something different from the original span a (same type)."""
    if typ == "TURN-START":
        return turn_type(a) != turn_type(b)
    if typ == "TOOL-NAME":
        return tool_name(a) != tool_name(b)
    (va, da), (vb, db) = arg_value(a), arg_value(b)
    if da and db:
        return va != vb
    if da or db:  # one side cut off by the token window: alias if it is a prefix of the other
        part, whole = (vb, va) if da else (va, vb)
        return not whole.startswith(part)
    return not (va.startswith(vb) or vb.startswith(va))


# ---------- candidates for one transcript ----------
def find_candidates(text, ids, offsets, lps):
    """-> (candidates, stats, n_straddle). stats[i] = (pos, p1, p2, H) for every assistant token with a logprob entry."""
    mask = assistant_mask(text, offsets)
    stats, info = {}, {}
    for i, e in enumerate(lps):
        if e is None or not mask[i]:
            continue
        top, p1, p2, H = lp_stats(e)
        stats[i] = (p1, p2, H)
        info[i] = top
    dec, strad = type_tokens(offsets, spans(text))
    cands = []
    for d in dec:
        i = d["pos"]
        if i not in info or len(info[i]) < 2:
            continue
        top = info[i]
        p1, p2, H = stats[i]
        if not is_candidate(p1, p2, top[0][0] == ids[i]):
            continue
        s = d["span"]
        j = min(i + ALIAS_TOKENS, len(ids) - 1)
        orig = text[offsets[i][0]:offsets[j][1]].split(END)[0]
        cands.append(dict(type=s["type"], turn=s["turn"], pos=i, char=offsets[i][0], p1=p1, p2=p2, H=H, orig_id=ids[i], forced_id=top[1][0], orig_span=orig))
    return cands, stats, strad


# ---------- server ----------
class Server:
    def __init__(self, base, model, api_key="none", retries=4, conc=8):
        import httpx
        self.base, self.model, self.retries = base.rstrip("/"), model, retries
        self.http = httpx.AsyncClient(timeout=600, headers={"Authorization": f"Bearer {api_key}"})
        self.sem = asyncio.Semaphore(conc)

    async def post(self, body):
        async with self.sem:
            for i in range(self.retries + 1):
                try:
                    r = await self.http.post(self.base + "/completions", json=dict(model=self.model, **body))
                    r.raise_for_status()
                    return r.json()["choices"][0]
                except Exception:
                    if i == self.retries:
                        raise
                    await asyncio.sleep(2 ** i)

    async def prompt_logprobs(self, ids):
        c = await self.post(dict(prompt=ids, max_tokens=1, temperature=0, prompt_logprobs=TOPK))
        lp = c.get("prompt_logprobs")
        if not lp or len(lp) != len(ids):
            raise RuntimeError(f"server returned prompt_logprobs of length {len(lp) if lp else None}, expected {len(ids)}")
        return lp

    async def greedy(self, ids, n):
        c = await self.post(dict(prompt=ids, max_tokens=n, temperature=0, skip_special_tokens=False))
        return c["text"]


async def alias_filter(srv, tok, ids, cands):
    async def one(c):
        comp = await srv.greedy(ids[:c["pos"]] + [c["forced_id"]], ALIAS_TOKENS)
        c["forced_span"] = (tok.decode([c["forced_id"]]) + comp).split(END)[0]
        c["survives"] = differs(c["type"], c["orig_span"], c["forced_span"])
    await asyncio.gather(*[one(c) for c in cands])
    return cands


async def analyse(srv, tok, task, rec, max_cand):
    msgs = build_messages(task, rec)
    if msgs is None:
        return dict(skipped="non-dict tool arguments")
    text = tok.render(msgs, TOOLS)
    ids, offs = tok.encode(text)
    if len(ids) > MAX_LEN:
        return dict(skipped=f"{len(ids)} tokens > {MAX_LEN}")
    lps = await srv.prompt_logprobs(ids)
    cands, stats, strad = find_candidates(text, ids, offs, lps)
    n_cands = len(cands)
    cands = sorted(cands, key=lambda c: -c["p2"])[:max_cand]  # alias-check the most live runner-ups first (suggested)
    await alias_filter(srv, tok, ids, cands)
    return dict(n_tokens=len(ids), n_asst=len(stats), straddle=strad, n_cands=n_cands, cands=cands, stats=stats)


# ---------- replay equality (G2) ----------
NORMALISERS = [("iso_timestamp_with_seconds", re.compile(r"\d{4}-\d\d-\d\d[T ]\d\d:\d\d:\d\d(?:\.\d+)?Z?"), "<TS>"),
               ("uuid", re.compile(r"\b[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\b"), "<UUID>"),
               ("call_id", re.compile(r"\bcall_[0-9a-f]{8}\b"), "<ID>")]


def normalise_out(s, fired=None):
    for name, rx, rep in NORMALISERS:
        t = rx.sub(rep, s)
        if t != s and fired is not None:
            fired[name] += 1
        s = t
    return s


def replay_prefix(task, msgs, upto, fired=None):
    """Replay every tool call in msgs[:upto+1] into a fresh World. -> (n_outputs, list of (expected, got) mismatches, n_raw_equal)."""
    w = World.from_json(task["state"])
    want = {m.get("tool_call_id"): m["content"] for m in msgs if m["role"] == "tool"}
    n, bad, raw = 0, [], 0
    for m in msgs[:upto + 1]:
        for c in (m.get("tool_calls") or []) if m["role"] == "assistant" else []:
            f = c["function"]
            a = f["arguments"]
            if isinstance(a, str):
                try:
                    a = json.loads(a) if a.strip() else {}
                except json.JSONDecodeError:
                    pass
            got, exp = w.call(f["name"], a), want.get(c["id"])
            n += 1
            raw += got == exp
            if normalise_out(got, fired) != normalise_out(exp or "", fired):
                bad.append((exp, got))
    return n, bad, raw


def replay_report(tasks, rows, per_type=PREFIXES_PER_TYPE, seed=0):
    rng, pool, fired = random.Random(seed), defaultdict(dict), Counter()
    for r in rows:
        t = tasks[r["task_id"]]
        for k, m in enumerate(r["transcript"]):
            if m["role"] == "assistant" and m.get("tool_calls"):
                prefix = json.dumps([[c["function"]["name"], c["function"]["arguments"]] for x in r["transcript"][:k + 1] if x.get("tool_calls") for c in x["tool_calls"]], sort_keys=True)
                pool[t["scenario"]].setdefault((t["id"], prefix), (t, r["transcript"], k))
    res = {}
    for sc, d in sorted(pool.items()):
        keys = sorted(d)
        rng.shuffle(keys)
        n_pref = n_out = n_bad = n_raw = 0
        ex = []
        for key in keys[:per_type]:
            t, tr, k = d[key]
            n, bad, raw = replay_prefix(t, tr, k, fired)
            n_pref, n_out, n_bad, n_raw = n_pref + 1, n_out + n, n_bad + (1 if bad else 0), n_raw + raw
            if bad and len(ex) < 2:
                ex.append(dict(task=t["id"], expected=bad[0][0][:200], got=bad[0][1][:200]))
        res[sc] = dict(prefixes=n_pref, outputs=n_out, prefixes_unequal=n_bad, outputs_raw_equal=n_raw, examples=ex)
    tot = sum(v["prefixes"] for v in res.values())
    return dict(per_scenario=res, prefixes=tot, unequal=sum(v["prefixes_unequal"] for v in res.values()),
                outputs=sum(v["outputs"] for v in res.values()), raw_equal=sum(v["outputs_raw_equal"] for v in res.values()),
                normalisers_fired=dict(fired), passed=tot > 0 and all(v["prefixes_unequal"] == 0 for v in res.values()))


# ---------- G3: classify check kinds ----------
def check_kinds(checks_path, used=None):
    src = open(checks_path).read()
    tree = ast.parse(src)
    fn = next(n for n in ast.walk(tree) if isinstance(n, ast.FunctionDef) and n.name == "run_check")
    kinds = {}
    for n in ast.walk(fn):
        if isinstance(n, ast.If) and isinstance(n.test, ast.Compare) and isinstance(n.test.left, ast.Name) and n.test.left.id == "t" \
                and isinstance(n.test.comparators[0], ast.Constant):
            body = "\n".join(ast.get_source_segment(src, b) or "" for b in n.body)
            uses_reply = re.search(r"\breply\b", body) is not None
            kinds[n.test.comparators[0].value] = "reply" if uses_reply else ("end-state" if re.search(r"\bw\.", body) else "other")
    nondet = sorted(set(re.findall(r"\b(random|time|datetime|uuid|os\.environ)\b", src)))
    ns = {}
    exec(compile(ast.Module([n for n in tree.body if isinstance(n, ast.Assign) and n.targets[0].id == "CHECK_KEYS"], []), checks_path, "exec"), ns)
    declared = sorted(ns["CHECK_KEYS"])
    unclassified = [k for k in declared if kinds.get(k) not in ("end-state", "reply")]
    used = used or {}
    return dict(kinds=kinds, declared=declared, unclassified=unclassified, nondeterminism_imports=nondet, used_in_T=dict(used),
                passed=not unclassified and not nondet and all(k in kinds for k in used),
                note="reply checks take the final reply of whatever run is scored (run_checks(task, world, reply)), so they are re-run on a continuation's own reply")


# ---------- gate ----------
def verdict(per_task, g2, g3, n_T=None):
    """per_task: {task_id: {'survivors': n, 'by_type': {...}}} for tasks that had a failed transcript."""
    n = len(per_task)
    ok = [t for t, v in per_task.items() if v["survivors"] >= G1_FORKS]
    share = len(ok) / n if n else 0.0
    g1 = dict(tasks=n, tasks_in_T=n_T, tasks_with_ge8=len(ok), share=round(share, 3), passed=n > 0 and share >= G1_SHARE)
    tot = Counter()
    for v in per_task.values():
        tot.update(v["by_type"])
    s = sum(tot.values())
    return dict(G1=g1, G2=dict(passed=bool(g2["passed"])), G3=dict(passed=bool(g3["passed"])), survivors_by_type=dict(tot),
                turn_start_share=round(tot["TURN-START"] / s, 3) if s else 0.0, go=bool(g1["passed"] and g2["passed"] and g3["passed"]))


def pick_transcripts(rows, T, per_task=PER_TASK):
    by = defaultdict(list)
    for r in rows:
        if r["arm"] in ("IND", "plain") and not r["success"] and r["task_id"] in T:
            by[r["task_id"]].append(r)
    return {t: sorted(v, key=lambda r: (r["arm"] != "IND", r["try_idx"]))[:per_task] for t, v in by.items()}


def report_md(g, per_task, scen):
    L = ["# Doubt Forks Step 0 gate", "", f"**{'GO' if g['go'] else 'NO-GO'}**  (G1 {g['G1']['passed']}, G2 {g['G2']['passed']}, G3 {g['G3']['passed']})", "",
         "Labels: shown = measured in this run; suggested = a heuristic chosen here; untested = not checked.", "",
         f"## G1 (shown): >= {G1_FORKS} surviving forks on >= {int(G1_SHARE * 100)}% of tasks",
         f"{g['G1']['tasks_with_ge8']} of {g['G1']['tasks']} tasks with a failed transcript pass ({g['G1']['share']:.0%}); T has {g['G1']['tasks_in_T']} tasks.", "",
         f"Surviving forks by type: {g['survivors_by_type']}. TURN-START share: {g['turn_start_share']:.0%}.", "",
         "| task | scenario | transcripts | candidates (T/N/A) | survivors (T/N/A) | total |", "|---|---|---|---|---|---|"]
    for t, v in sorted(per_task.items()):
        c, s = v["cand_by_type"], v["by_type"]
        L.append(f"| {t} | {scen.get(t, '')} | {v['transcripts']} | {c.get('TURN-START', 0)}/{c.get('TOOL-NAME', 0)}/{c.get('ARG-VALUE', 0)} | "
                 f"{s.get('TURN-START', 0)}/{s.get('TOOL-NAME', 0)}/{s.get('ARG-VALUE', 0)} | {v['survivors']} |")
    r = g["replay"]
    L += ["", f"## G2 (shown): replay equality: {'PASS' if g['G2']['passed'] else 'FAIL'}",
          f"{r['prefixes']} prefixes ({r['outputs']} tool outputs; {r['raw_equal']} equal before normalising); unequal prefixes {r['unequal']}; normalisers that fired: {r['normalisers_fired'] or 'none'}.", "",
          "| scenario | prefixes | outputs | unequal prefixes |", "|---|---|---|---|"]
    L += [f"| {k} | {v['prefixes']} | {v['outputs']} | {v['prefixes_unequal']} |" for k, v in r["per_scenario"].items()]
    for k, v in r["per_scenario"].items():
        for e in v["examples"]:
            L.append(f"\nMismatch {k} {e['task']}: expected `{e['expected']}` got `{e['got']}`")
    c = g["checks"]
    L += ["", f"## G3 (shown, static read of checks.py): {'PASS' if g['G3']['passed'] else 'FAIL'}", "",
          "| check kind | class | uses in T |", "|---|---|---|"]
    L += [f"| {k} | {v} | {c['used_in_T'].get(k, 0)} |" for k, v in sorted(c["kinds"].items())]
    L += ["", c["note"] + f". Unclassified: {c['unclassified'] or 'none'}. Nondeterminism imports: {c['nondeterminism_imports'] or 'none'}.", "",
          f"## Run notes", f"- {g['notes']}", "- Heuristics (suggested): the candidate must be the token actually taken (argmax); the forced token is rank 2; turn type = tool call / contains '?' / other; "
          "alias windows are 25 tokens; at most `--max-cand` candidates per transcript are alias-checked, highest p2 first.",
          "- Distinct forks per task are keyed by (type, turn, original value, forced value)."]
    return "\n".join(L) + "\n"


# ---------- driver ----------
def load_tasks():
    d = os.path.join(R1, "rlaif_copy", "data")
    return [json.loads(l) for f in ("tasks_train.jsonl", "tasks_heldout.jsonl") for l in open(os.path.join(d, f)) if l.strip()]


async def run(a, tok=None, srv=None):
    rows = [json.loads(l) for l in open(a.results) if l.strip()]
    tp = a.target or os.path.join(os.path.dirname(os.path.abspath(a.results)), "target.json")
    T = json.load(open(tp))["T"]
    tasks = {t["id"]: t for t in load_tasks()}
    tok = tok or HFTok(a.tokenizer, a.template)
    srv = srv or Server(a.base_url, a.model, a.api_key, conc=a.concurrency)
    sel = pick_transcripts(rows, set(T), a.per_task)
    os.makedirs(a.out, exist_ok=True)
    jobs = [(tid, r) for tid in T for r in sel.get(tid, [])]
    if a.limit:
        jobs = jobs[:a.limit]
    results = await asyncio.gather(*[analyse(srv, tok, tasks[tid], r, a.max_cand) for tid, r in jobs])
    per_task, skipped, strad = {}, [], 0
    with open(os.path.join(a.out, "forks.jsonl"), "w") as ff, open(os.path.join(a.out, "token_stats.jsonl"), "w") as fs:
        for (tid, r), res in zip(jobs, results):
            if "skipped" in res:
                skipped.append((tid, r["try_idx"], res["skipped"]))
                continue
            strad += res["straddle"]
            fs.write(json.dumps(dict(task_id=tid, arm=r["arm"], try_idx=r["try_idx"], tokens={str(i): [round(x, 5) for x in v] for i, v in res["stats"].items()})) + "\n")
            pt = per_task.setdefault(tid, dict(transcripts=0, keys=set(), cand_by_type=Counter(), by_type=Counter(), survivors=0))
            pt["transcripts"] += 1
            for c in res["cands"]:
                pt["cand_by_type"][c["type"]] += 1
                ff.write(json.dumps(dict(task_id=tid, arm=r["arm"], try_idx=r["try_idx"], **c), ensure_ascii=False) + "\n")
                if c["survives"]:
                    k = (c["type"], c["turn"], norm(c["orig_span"])[:60], norm(c["forced_span"])[:60])
                    if k not in pt["keys"]:
                        pt["keys"].add(k)
                        pt["by_type"][c["type"]] += 1
                        pt["survivors"] += 1
    for v in per_task.values():
        v.pop("keys")
        v["cand_by_type"], v["by_type"] = dict(v["cand_by_type"]), dict(v["by_type"])
    pool = [r for r in rows if r["arm"] in ("IND", "plain") and r["task_id"] in set(T)]
    g2 = replay_report(tasks, pool, a.prefixes_per_type)
    used = Counter(c["type"] for tid in T for c in tasks[tid]["checks"])
    g3 = check_kinds(os.path.join(R1, "rlaif_copy", "checks.py"), used)
    g = verdict(per_task, g2, g3, len(T))
    g |= dict(replay=g2, checks=g3, per_task=per_task, notes=f"{len(jobs)} transcripts analysed, {len(skipped)} skipped {skipped[:5]}, {strad} decision spans skipped (token straddles the span start)")
    json.dump(g, open(os.path.join(a.out, "gate.json"), "w"), indent=1, ensure_ascii=False)
    open(os.path.join(a.out, "gate.md"), "w").write(report_md(g, per_task, {t: tasks[t]["scenario"] for t in per_task}))
    print(f"Step 0: {'GO' if g['go'] else 'NO-GO'}  G1 {g['G1']}  G2 {g['G2']}  G3 {g['G3']}  TURN-START share {g['turn_start_share']}")
    return g


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__)
